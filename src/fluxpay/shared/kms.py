"""Cryptographic Key Management System (KMS) and Abstract Signer Architecture.

Provides the foundational security boundary for signing Ethereum Virtual Machine (EVM)
transactions and cryptographic messages across Base L2 (chain_id=8453) and Base Sepolia (84532).

Security Invariants & Architectural Laws:
1. THE ABSOLUTE ZERO IN-MEMORY KEY LAW:
   Private keys must NEVER enter application process memory in production. All signing
   operations must be delegated to dedicated Hardware Security Modules (HSMs) or Cloud
   KMS enclaves (AWS KMS, GCP Cloud KMS, Azure Key Vault, YubiHSM 2, Fireblocks MPC).
2. THE FAIL-CLOSED LAW:
   If a KMS service is unreachable, throttled, or returns an unverified signature,
   the platform FAILS CLOSED. It will NEVER fall back to local software keys or bypass
   signature verification.
3. THE SIGNATURE FRESHNESS & NON-CACHEABILITY LAW:
   Cryptographic signatures must NEVER be cached or memoized. Every transaction nonce
   and authorization signature must be freshly generated by the hardware enclave.
4. SINK-LEVEL SECRET REDACTION:
   Private keys, seed phrases, unsigned/signed transaction hex, and raw key IDs are
   STRICTLY forbidden from appearing in logs, metrics, or exception strings. Key IDs are
   obfuscated using truncated SHA-256 digests in structured logging events.
5. MANDATORY LOCAL ADDRESS VERIFICATION:
   Every signature produced by a remote HSM/KMS must be locally verified via public
   key recovery prior to returning raw signed bytes. If the recovered address does not
   match the configured hot-wallet address, the signature is immediately discarded
   and an operational alarm is triggered.
"""

