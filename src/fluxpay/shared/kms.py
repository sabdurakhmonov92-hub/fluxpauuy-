# Signer Registry for Zero-Downtime Key Rotation
# -----------------------------------------------------------------------------
class SignerRegistry:
    """Thread-safe registry mapping key identifiers to active Signer instances.

    Facilitates zero-downtime key rotation:
    - Primary key is used for signing all new outbound transactions.
    - Secondary/previous keys remain registered to verify in-flight authorizations.
    """

    def __init__(self, *, primary_key_id: str | None = None) -> None:
        self._signers: dict[str, Signer] = {}
        self._primary_key_id: str | None = primary_key_id

    def register(self, key_id: str, signer: Signer, *, is_primary: bool = False) -> None:
        """Register a Signer instance under a specific key identifier.

        Args:
            key_id: Unique key identifier or alias.
            signer: Initialized Signer instance.
            is_primary: Whether this key is the default signing key.
        """
        self._signers[key_id] = signer
        if is_primary or self._primary_key_id is None:
            self._primary_key_id = key_id

    def get(self, key_id: str) -> Signer:
        """Retrieve a registered Signer by key ID.

        Args:
            key_id: Key identifier.

        Returns:
            Matching Signer instance.

        Raises:
            KmsKeyNotFoundError: If key_id is not registered.
        """
        if key_id not in self._signers:
            raise KmsKeyNotFoundError(
                message=f"No signer registered for key ID: {hash_key_id(key_id)}",
                details={"key_fingerprint": hash_key_id(key_id)},
            )
        return self._signers[key_id]

    def get_primary(self) -> Signer:
        """Retrieve the primary signing key instance.

        Returns:
            Primary Signer instance.

        Raises:
            KmsKeyNotFoundError: If no primary key is configured.
        """
        if self._primary_key_id is None or self._primary_key_id not in self._signers:
            raise KmsKeyNotFoundError(message="No primary signer registered in SignerRegistry")
        return self._signers[self._primary_key_id]

    def set_primary(self, key_id: str) -> None:
        """Promote an existing registered key to primary status.

        Args:
            key_id: Key identifier to promote.

        Raises:
            KmsKeyNotFoundError: If key_id is not already registered.
        """
        if key_id not in self._signers:
            raise KmsKeyNotFoundError(
                message=f"Cannot promote unregistered key ID: {hash_key_id(key_id)}",
                details={"key_fingerprint": hash_key_id(key_id)},
            )
        self._primary_key_id = key_id

    def has_key(self, key_id: str) -> bool:
        """Check whether a key ID is currently registered."""
        return key_id in self._signers

    def list_keys(self) -> list[str]:
        """Return list of all registered key IDs."""
        return list(self._signers.keys())
