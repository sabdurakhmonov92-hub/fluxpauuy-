# SECP256k1 curve order constants for canonical low-s signature enforcement (EIP-2)
SECP256K1_N: Final[int] = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
SECP256K1_HALF_N: Final[int] = SECP256K1_N // 2


def hash_key_id(key_id: str) -> str:
    """Return a truncated SHA-256 fingerprint of a KMS key identifier.

    Prevents raw AWS ARNs, GCP version paths, or vault URLs from being exposed in logs.
    """
    return hashlib.sha256(key_id.encode("utf-8")).hexdigest()[:16]


