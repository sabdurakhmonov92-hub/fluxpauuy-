class KMSError(IntegrationError):
    """Base error for all cryptographic key management failures."""

    def __init__(
        self,
        message: str,
        *,
        code: str,
        details: dict[str, str] | None = None,
        retryable: bool = False,
    ) -> None:
        merged_details = {"code": code}
        if details is not None:
            merged_details.update(details)
        super().__init__(message=message, details=merged_details)
        self.code = code
        self.retryable = retryable


class KmsUnavailableError(KMSError):
    """Raised when KMS/HSM service endpoint is temporarily unreachable or times out."""

    def __init__(
        self,
        message: str = "KMS service temporarily unavailable",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="KMS_UNAVAILABLE", details=details, retryable=True)


class KmsAccessDeniedError(KMSError):
    """Raised when IAM credentials or vault access policy denies key usage (fail-closed)."""

    def __init__(
        self,
        message: str = "KMS access denied by security policy",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="KMS_ACCESS_DENIED", details=details, retryable=False)


class KmsThrottledError(KMSError):
    """Raised when KMS rate limits or API TPS quotas are exceeded (retry with jitter)."""

    def __init__(
        self,
        message: str = "KMS signing request throttled by provider",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="KMS_THROTTLED", details=details, retryable=True)


class KmsInvalidSignatureError(KMSError):
    """Raised when KMS returns malformed DER ASN.1 data or invalid elliptic curve scalars."""

    def __init__(
        self,
        message: str = "KMS returned malformed or unparseable signature",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="KMS_INVALID_SIGNATURE", details=details, retryable=False)


class KmsKeyNotFoundError(KMSError):
    """Raised when requested key ID, alias, or key version is missing from the vault."""

    def __init__(
        self,
        message: str = "KMS signing key was not found",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="KMS_KEY_NOT_FOUND", details=details, retryable=False)


class AddressMismatchError(KMSError):
    """Raised when locally recovered address does not match expected EIP-55 address (CRITICAL)."""

    def __init__(
        self,
        message: str = "Recovered signer address does not match expected address",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(message, code="ADDRESS_MISMATCH", details=details, retryable=False)


class SignatureVerificationFailedError(KMSError):
    """Raised when signature fails mathematical verification against public key (CRITICAL)."""

    def __init__(
        self,
        message: str = "Cryptographic signature verification failed",
        *,
        details: dict[str, str] | None = None,
    ) -> None:
        super().__init__(
            message,
            code="SIGNATURE_VERIFICATION_FAILED",
            details=details,
            retryable=False,
        )


