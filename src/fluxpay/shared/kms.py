@runtime_checkable
class Signer(Protocol):
    """Abstract protocol for signing Base L2 EVM transactions and messages."""

    async def get_address(self) -> str:
        """Return EIP-55 checksummed Ethereum address."""
        ...

    async def sign_transaction(self, tx: dict[str, Any]) -> bytes:
        """Sign an EIP-1559 transaction dict and return raw signed transaction bytes."""
        ...

    async def sign_message(self, message: bytes) -> bytes:
        """Sign an arbitrary byte payload conforming to EIP-191 personal_sign."""
        ...

    async def sign_typed_data(self, typed_data: dict[str, Any]) -> bytes:
        """Sign an EIP-712 structured typed data object."""
        ...


class BaseSigner(ABC):
    """Abstract base class implementing shared EVM cryptographic operations and security laws.

    Provides canonical EIP-2 low-s normalization, recovery ID determination,
    address verification, and sanitized string representations.
    """

    def __init__(self, *, address: str) -> None:
        self._address: Final[str] = Web3.to_checksum_address(address)

    @property
    def address(self) -> str:
        """Return EIP-55 checksummed address (supports legacy TxSigner interface)."""
        return self._address

    async def get_address(self) -> str:
        """Return EIP-55 checksummed address conforming to Signer protocol."""
        return self._address

    @abstractmethod
    async def sign_transaction(self, tx: dict[str, Any]) -> bytes:
        """Sign an EIP-1559 transaction dict and return raw signed transaction bytes."""
        ...

    @abstractmethod
    async def sign_message(self, message: bytes) -> bytes:
        """Sign an arbitrary byte payload conforming to EIP-191."""
        ...

    @abstractmethod
    async def sign_typed_data(self, typed_data: dict[str, Any]) -> bytes:
        """Sign an EIP-712 structured typed data object."""
        ...

    @staticmethod
    def normalize_s(s: int) -> int:
        """Enforce canonical low-s values to prevent transaction malleability (EIP-2).

        Args:
            s: Raw signature scalar s.

        Returns:
            Normalized s where s <= SECP256K1_N // 2.
        """
        if s > SECP256K1_HALF_N:
            return SECP256K1_N - s
        return s

    @staticmethod
    def parse_der_or_raw_signature(sig_bytes: bytes) -> tuple[int, int]:
        """Parse raw 64-byte (r || s) or DER ASN.1 ECDSA signature.

        Args:
            sig_bytes: Raw signature bytes returned by KMS/HSM.

        Returns:
            Tuple of integer scalars (r, s).

        Raises:
            KmsInvalidSignatureError: If signature is malformed or scalars out of range.
        """
        try:
            if len(sig_bytes) == 64:
                r = int.from_bytes(sig_bytes[:32], "big")
                s = int.from_bytes(sig_bytes[32:], "big")
            else:
                r, s = decode_dss_signature(sig_bytes)
        except Exception as exc:
            raise KmsInvalidSignatureError(
                message=f"Failed to parse DER/raw signature: {exc}",
                details={"len": str(len(sig_bytes))},
            ) from exc

        # Cryptographic range check: 1 <= r, s < SECP256K1_N
        if not (1 <= r < SECP256K1_N and 1 <= s < SECP256K1_N):
            raise KmsInvalidSignatureError(
                message="Signature scalars r or s fall outside SECP256k1 valid range",
                details={
                    "r_valid": str(1 <= r < SECP256K1_N),
                    "s_valid": str(1 <= s < SECP256K1_N),
                },
            )

        return r, s

    def determine_recovery_id(self, digest: bytes, r: int, s: int) -> int:
        """Compute the Ethereum ECDSA recovery ID (v = 0 or 1) by trial recovery.

        Verifies that the recovered address matches the configured signer address.
        Constant-time string comparison is enforced via hmac.compare_digest.

        Args:
            digest: 32-byte keccak256 hash that was signed.
            r: Elliptic curve scalar r.
            s: Normalized low-s scalar.

        Returns:
            Recovery identifier v (0 or 1).

        Raises:
            AddressMismatchError: If neither candidate v recovers to the configured address.
        """
        for candidate_v in (0, 1):
            try:
                recovered = Account._recover_hash(digest, vrs=(candidate_v, r, s))
                if hmac.compare_digest(recovered.lower(), self._address.lower()):
                    return candidate_v
            except Exception as exc:
                _logger.debug(
                    "kms_recovery_id_failed_candidate",
                    candidate_v=candidate_v,
                    error=str(exc),
                )
                continue

        raise AddressMismatchError(
            message="KMS signature failed local address recovery check",
            details={"configured_address": self._address},
        )

    @staticmethod
    def hash_eip1559_transaction(tx_dict: dict[str, Any]) -> tuple[dict[str, Any], bytes]:
        """Compute the canonical 32-byte signing hash of an unsigned EIP-1559 transaction dict.

        Args:
            tx_dict: Unsigned transaction dictionary.

        Returns:
            Tuple of (clean_tx_dict_without_from, 32_byte_tx_hash).
        """
        clean_tx = {k: v for k, v in tx_dict.items() if k != "from"}
        unsigned_tx = serializable_unsigned_transaction_from_dict(clean_tx)
        return clean_tx, bytes(unsigned_tx.hash())

    def assemble_eip1559_signed_transaction(
        self,
        unsigned_tx_dict: dict[str, Any],
        v: int,
        r: int,
        s: int,
    ) -> bytes:
        """RLP-encode signed EIP-1559 Type-2 transaction bytes.

        Args:
            unsigned_tx_dict: Transaction payload dictionary.
            v: Recovery ID (0 or 1).
            r: Elliptic curve scalar r.
            s: Normalized low-s scalar.

        Returns:
            Raw serialized transaction bytes ready for broadcast.
        """
        clean_tx = {k: v for k, v in unsigned_tx_dict.items() if k != "from"}
        unsigned_tx = serializable_unsigned_transaction_from_dict(clean_tx)
        signed_bytes = encode_transaction(unsigned_tx, vrs=(v, r, s))
        return bytes(signed_bytes)

    @staticmethod
    def assemble_65byte_signature(r: int, s: int, v: int) -> bytes:
        """Assemble canonical 65-byte Ethereum signature (r || s || v).

        Args:
            r: Scalar r.
            s: Normalized scalar s.
            v: Recovery identifier (0/1 or 27/28).

        Returns:
            65 bytes containing (r: 32 bytes, s: 32 bytes, v: 1 byte).
        """
        standard_v = 27 + v if v in (0, 1) else v
        return r.to_bytes(32, "big") + s.to_bytes(32, "big") + bytes([standard_v])

    def __repr__(self) -> str:
        """Redact sensitive fields; only expose class name and verified address."""
        return f"<{self.__class__.__name__} address='{self._address}'>"

    def __str__(self) -> str:
        return f"{self.__class__.__name__}({self._address})"


