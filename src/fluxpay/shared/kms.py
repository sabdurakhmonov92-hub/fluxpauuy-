class MPCSigner(BaseSigner, ABC):
    """Abstract base class for Multi-Party Computation (MPC) signing backends.

    Handles asynchronous distributed threshold signing workflows (Fireblocks, Qredo, Copper).
    """

    @abstractmethod
    async def initiate_signing(self, message_hash: bytes) -> str:
        """Initiate asynchronous MPC signing operation and return an operation ID.

        Args:
            message_hash: 32-byte keccak256 digest to sign.

        Returns:
            External MPC operation or transaction tracking ID.
        """
        ...

    @abstractmethod
    async def poll_signature(
        self,
        operation_id: str,
        *,
        timeout_s: float = 30.0,
    ) -> tuple[int, int, int]:
        """Poll MPC threshold nodes until signature quorum is reached.

        Args:
            operation_id: External operation tracking ID.
            timeout_s: Maximum duration to wait before timing out.

        Returns:
            Tuple of (v, r, s).
        """
        ...


