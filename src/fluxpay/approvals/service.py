# APPROVAL SERVICE
# ==============================================================================
class ApprovalService:
    """Orchestrates 2-man quorum voting, hold state transitions, and settlement."""

    def __init__(
        self,
        pool: asyncpg.Pool,
        bus: EventBus,
        notifier: AdminNotifier | None = None,
        payments: PaymentService | None = None,
    ) -> None:
        self._pool = pool
        self._bus = bus
        self._notifier: AdminNotifier = notifier if notifier is not None else LoggingAdminNotifier()
        self._payments = payments

    async def submit_vote(
        self,
        *,
        hold_id: UUID,
        voter_sub: str,
        voter_role: str,
        vote: str,
        note: str = "",
    ) -> VoteOutcome:
        """Submit a vote on a quarantined payment hold.

        Enforces:
        - Admin role verification (403 ForbiddenError on non-admin).
        - Vote validation ('approve' | 'reject').
        - Hold existence and status='pending' (409 HoldNotPendingError if not pending).
        - Self/duplicate vote prevention via DB UNIQUE(hold_id, voter_sub).
        - Atomic UoW committing vote + decide + audit.
        - Two-phase settlement execution after commit.
        """
        # 1. Role validation (separation of duties)
        check_voter_role(voter_role)

        # 2. Vote input validation
        if vote not in ("approve", "reject"):
            raise ValidationError(
                message="Request payload failed validation.",
                details={"field": "vote", "reason": "must be 'approve' or 'reject'"},
            )

        # 3. Note truncation policy: max 200 characters app-side
        truncated_note = note[:200]

        hold: HoldRecord | None = None
        action_after_commit: str = "counted"
        votes_for: int = 0
        votes_against: int = 0

        # Phase 1: Unit of Work transaction
        try:
            async with UnitOfWork(self._pool) as uow:
                # Assert hold exists and is in 'pending' status with row-level lock
                row = await uow.connection.fetchrow(
                    """
                    SELECT
                        hold_id, agent_id, idem_key, amount_minor, currency,
                        reason, status, payload, created_at, updated_at
                    FROM payment_holds
                    WHERE hold_id = $1
                    FOR UPDATE;
                    """,
                    hold_id,
                )
                if row is None:
                    raise NotFoundError(
                        details={"hold_id": str(hold_id)},
                        message="The requested payment hold was not found.",
                    )

                hold_status = str(row["status"])
                if hold_status != "pending":
                    raise HoldNotPendingError(
                        details={"hold_id": str(hold_id), "status": hold_status},
                        message=f"Hold {hold_id} is in status '{hold_status}', not 'pending'.",
                    )

                raw_payload = row["payload"]
                payload_data: dict[str, Any] = (
                    orjson.loads(raw_payload)
                    if isinstance(raw_payload, (str, bytes))
                    else dict(raw_payload)
                )

                hold = HoldRecord(
                    hold_id=row["hold_id"],
                    agent_id=row["agent_id"],
                    idem_key=row["idem_key"],
                    amount_minor=row["amount_minor"],
                    currency=row["currency"],
                    reason=row["reason"],
                    status=hold_status,
                    created_at=row["created_at"],
                    payload=payload_data,
                    updated_at=row["updated_at"],
                )

                # Query existing votes
                existing_votes = await uow.connection.fetch(
                    """
                    SELECT voter_sub, vote
                    FROM approval_votes
                    WHERE hold_id = $1;
                    """,
                    hold_id,
                )
                voters = {r["voter_sub"] for r in existing_votes}
                cur_for = sum(1 for r in existing_votes if r["vote"] == "approve")
                cur_against = sum(1 for r in existing_votes if r["vote"] == "reject")

                # Duplicate vote check (application-level guard)
                if voter_sub in voters:
                    return VoteOutcome(
                        status="already_voted",
                        votes_for=cur_for,
                        votes_against=cur_against,
                    )

                # Insert new vote record (database-level UNIQUE constraint guard)
                await uow.connection.execute(
                    """
                    INSERT INTO approval_votes (hold_id, voter_sub, vote, note, voted_at)
                    VALUES ($1, $2, $3, $4, now());
                    """,
                    hold_id,
                    voter_sub,
                    vote,
                    truncated_note,
                )

                # Audit vote recording (commits atomically with UoW)
                await audit.record(
                    uow.connection,
                    actor_sub=voter_sub,
                    actor_role=voter_role,
                    action="hold.vote",
                    target_type="agent",
                    target_id=str(hold.agent_id),
                    details={
                        "hold_id": str(hold_id),
                        "vote": vote,
                        "note": truncated_note,
                    },
                )

                votes_for = cur_for + (1 if vote == "approve" else 0)
                votes_against = cur_against + (1 if vote == "reject" else 0)

                # Evaluate quorum decision
                if REJECTS_TERMINAL and votes_against >= 1:
                    # Reject path: single rejection kills hold immediately
                    await uow.connection.execute(
                        """
                        UPDATE payment_holds
                        SET status = 'rejected', updated_at = now()
                        WHERE hold_id = $1 AND status = 'pending';
                        """,
                        hold_id,
                    )
                    # Task 11 idempotency fail (marks reservation FAILED)
                    await idempotency_fail(uow.connection, hold.agent_id, hold.idem_key)

                    # Audit reject recording
                    await audit.record(
                        uow.connection,
                        actor_sub=voter_sub,
                        actor_role=voter_role,
                        action="hold.reject",
                        target_type="agent",
                        target_id=str(hold.agent_id),
                        details={
                            "hold_id": str(hold_id),
                            "reason": "rejected_by_approver",
                            "note": truncated_note,
                        },
                    )
                    action_after_commit = "reject"

                elif votes_for >= VOTES_REQUIRED:
                    # Approve path: 2-man threshold reached
                    await uow.connection.execute(
                        """
                        UPDATE payment_holds
                        SET status = 'approved', updated_at = now()
                        WHERE hold_id = $1 AND status = 'pending';
                        """,
                        hold_id,
                    )
                    # Audit approve2 recording
                    await audit.record(
                        uow.connection,
                        actor_sub=voter_sub,
                        actor_role=voter_role,
                        action="hold.approve2",
                        target_type="agent",
                        target_id=str(hold.agent_id),
                        details={
                            "hold_id": str(hold_id),
                            "votes_for": votes_for,
                        },
                    )
                    action_after_commit = "settle"
                else:
                    action_after_commit = "counted"

        except asyncpg.UniqueViolationError:
            # Concurrent race for the same voter identity tripped DB constraint.
            # UoW aborted cleanly; no audit rows committed for failed branch.
            async with self._pool.acquire() as conn:
                vote_rows = await conn.fetch(
                    "SELECT vote FROM approval_votes WHERE hold_id = $1;", hold_id
                )
                vf = sum(1 for r in vote_rows if r["vote"] == "approve")
                va = sum(1 for r in vote_rows if r["vote"] == "reject")
                return VoteOutcome(status="already_voted", votes_for=vf, votes_against=va)

        if hold is None:
            raise RuntimeError("Unexpected failure: hold record was not loaded")

        # Phase 2: Post-commit settlement and notification execution
        if action_after_commit == "reject":
            # Rejection broadcast & notification
            to_merchant = str(hold.payload.get("to_merchant") or hold.payload.get("merchant") or "")
            amount_minor = int(hold.payload.get("amount_minor") or hold.amount_minor)
            fee_minor = int(hold.payload.get("fee_minor") or 0)
            total_minor = int(hold.payload.get("total_minor") or hold.amount_minor)
            currency = str(hold.payload.get("currency") or hold.currency)
            tx_id = deterministic_tx_id(hold.agent_id, hold.idem_key)

            failed_event = make_event(
                type=EventType.PAYMENT_FAILED,
                payload={
                    "tx_id": str(tx_id),
                    "payment_id": str(tx_id),
                    "agent_id": str(hold.agent_id),
                    "merchant": to_merchant,
                    "amount": amount_minor,
                    "fee": fee_minor,
                    "total": total_minor,
                    "currency": currency,
                    "reason": "rejected_by_approver",
                },
                producer="fluxpay.approvals",
            )
            await self._bus.publish(failed_event)
            await self._notifier.notify_hold_rejected(hold, outcome="rejected")
            return VoteOutcome(
                status="rejected",
                votes_for=votes_for,
                votes_against=votes_against,
            )

        if action_after_commit == "settle":
            # Settlement through Task 31's settle_approved door
            if self._payments is None:
                raise RuntimeError(
                    "PaymentService must be configured on ApprovalService for settlement"
                )

            to_merchant = str(hold.payload.get("to_merchant") or hold.payload.get("merchant") or "")
            amount_minor = int(hold.payload.get("amount_minor") or hold.amount_minor)
            currency = str(hold.payload.get("currency") or hold.currency)

            outcome = await self._payments.settle_approved(
                agent_id=hold.agent_id,
                idem_key=hold.idem_key,
                to_merchant=to_merchant,
                amount_minor=amount_minor,
                currency=currency,
            )

            # Record audit "hold.settled" in its own independent UoW
            async with UnitOfWork(self._pool) as uow:
                await audit.record(
                    uow.connection,
                    actor_sub=voter_sub,
                    actor_role=voter_role,
                    action="hold.settled",
                    target_type="agent",
                    target_id=str(hold.agent_id),
                    details={
                        "hold_id": str(hold.hold_id),
                        "tx_id": str(outcome.tx_id),
                    },
                )

            await self._notifier.notify_hold_settled(hold, outcome)
            return VoteOutcome(
                status="approved_settled",
                votes_for=votes_for,
                votes_against=votes_against,
            )

        return VoteOutcome(
            status="counted",
            votes_for=votes_for,
            votes_against=votes_against,
        )


# ==============================================================================
# APPROVALS WORKER (NOTIFICATION & CRASH-HEAL SWEEP)
# ==============================================================================
@dataclass(frozen=True, slots=True)
class ApprovalWorkItem:
    """Item to be processed by ApprovalsWorker."""

    kind: Literal["notify_pending", "sweep_settle"]
    hold: HoldRecord


class ApprovalsWorker(Worker):
    """Continuous background worker for hold notification and crash-heal settlement."""

    def __init__(
        self,
        pool: asyncpg.Pool,
        bus: EventBus,
        notifier: AdminNotifier,
        payments: PaymentService,
        *,
        valkey: Any = None,
        poll_interval_s: float = 10.0,
        batch_size: int = 50,
        grace_seconds: float = 60.0,
        stop: asyncio.Event | None = None,
        sleeper: Callable[[float], Coroutine[Any, Any, None]] = asyncio.sleep,
        time_fn: Callable[[], datetime] = lambda: datetime.now(UTC),
    ) -> None:
        super().__init__(
            name="approvals_worker",
            pool=pool,
            valkey=valkey,
            bus=bus,
            poll_interval_s=poll_interval_s,
            batch_size=batch_size,
            stop=stop,
            sleeper=sleeper,
        )
        self._notifier = notifier
        self._payments = payments
        self._grace_seconds = grace_seconds
        self._time_fn = time_fn

    async def poll(self) -> Sequence[ApprovalWorkItem]:
        """Poll for unnotified pending holds and approved holds awaiting settlement."""
        items: list[ApprovalWorkItem] = []

        # (a) Unnotified pending holds
        async with self.pool.acquire() as conn:
            pending_rows = await conn.fetch(
                """
                SELECT
                    hold_id, agent_id, idem_key, amount_minor, currency,
                    reason, status, payload, created_at, updated_at
                FROM payment_holds
                WHERE status = 'pending' AND notified_at IS NULL
                ORDER BY created_at ASC
                LIMIT $1;
                """,
                self.batch_size,
            )

            for r in pending_rows:
                raw_payload = r["payload"]
                payload_data = (
                    orjson.loads(raw_payload)
                    if isinstance(raw_payload, (str, bytes))
                    else dict(raw_payload)
                )
                hold = HoldRecord(
                    hold_id=r["hold_id"],
                    agent_id=r["agent_id"],
                    idem_key=r["idem_key"],
                    amount_minor=r["amount_minor"],
                    currency=r["currency"],
                    reason=r["reason"],
                    status=str(r["status"]),
                    created_at=r["created_at"],
                    payload=payload_data,
                    updated_at=r["updated_at"],
                )
                items.append(ApprovalWorkItem(kind="notify_pending", hold=hold))

            # (b) Approved holds older than grace period (the crash-heal sweep)
            cutoff = self._time_fn() - timedelta(seconds=self._grace_seconds)
            approved_rows = await conn.fetch(
                """
                SELECT
                    hold_id, agent_id, idem_key, amount_minor, currency,
                    reason, status, payload, created_at, updated_at
                FROM payment_holds
                WHERE status = 'approved' AND updated_at < $1
                ORDER BY updated_at ASC
                LIMIT $2;
                """,
                cutoff,
                self.batch_size,
            )

            for r in approved_rows:
                raw_payload = r["payload"]
                payload_data = (
                    orjson.loads(raw_payload)
                    if isinstance(raw_payload, (str, bytes))
                    else dict(raw_payload)
                )
                hold = HoldRecord(
                    hold_id=r["hold_id"],
                    agent_id=r["agent_id"],
                    idem_key=r["idem_key"],
                    amount_minor=r["amount_minor"],
                    currency=r["currency"],
                    reason=r["reason"],
                    status=str(r["status"]),
                    created_at=r["created_at"],
                    payload=payload_data,
                    updated_at=r["updated_at"],
                )
                items.append(ApprovalWorkItem(kind="sweep_settle", hold=hold))

        return items

    async def process(self, batch: Sequence[Any]) -> None:
        """Process polled notifications and crash-heal sweep settlements."""
        # The worker is an automated operational mechanism, NEVER a decision-maker.
        # It never votes on holds; it only executes notifications and crash healing.
        for item in batch:
            if not isinstance(item, ApprovalWorkItem):
                continue

            if item.kind == "notify_pending":
                await self._process_notify_pending(item.hold)
            elif item.kind == "sweep_settle":
                await self._process_sweep_settle(item.hold)

    async def _process_notify_pending(self, hold: HoldRecord) -> None:
        """Dispatch operator notification and record notified_at marker."""
        await self._notifier.notify_hold_pending(hold)
        async with self.pool.acquire() as conn:
            await conn.execute(
                """
                UPDATE payment_holds
                SET notified_at = now()
                WHERE hold_id = $1 AND notified_at IS NULL;
                """,
                hold.hold_id,
            )

    async def _process_sweep_settle(self, hold: HoldRecord) -> None:
        """Probe idempotency state and execute crash-heal settlement if still pending."""
        async with self.pool.acquire() as conn:
            reservation = await idempotency_lookup(conn, hold.agent_id, hold.idem_key)

        if reservation is not None and reservation.outcome == ReservationOutcome.REPLAY:
            # COMPLETED with settled wire body; money already moved before crash. Skip.
            return

        to_merchant = str(hold.payload.get("to_merchant") or hold.payload.get("merchant") or "")
        amount_minor = int(hold.payload.get("amount_minor") or hold.amount_minor)
        currency = str(hold.payload.get("currency") or hold.currency)

        outcome = await self._payments.settle_approved(
            agent_id=hold.agent_id,
            idem_key=hold.idem_key,
            to_merchant=to_merchant,
            amount_minor=amount_minor,
            currency=currency,
        )

        async with UnitOfWork(self.pool) as uow:
            await audit.record(
                uow.connection,
                actor_sub="system:approvals_worker",
                actor_role="admin",
                action="hold.settled",
                target_type="agent",
                target_id=str(hold.agent_id),
                details={
                    "hold_id": str(hold.hold_id),
                    "tx_id": str(outcome.tx_id),
                    "source": "sweep",
                },
            )

        await self._notifier.notify_hold_settled(hold, outcome)

    async def run_once(self) -> int:
        """Execute a single poll and process cycle. Returns number of items processed."""
        batch = await self.poll()
        if batch:
            await self.process(batch)
        return len(batch)
