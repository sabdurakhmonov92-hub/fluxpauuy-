VoteStatus = Literal["counted", "approved_settled", "rejected", "already_voted"]


@dataclass(frozen=True, slots=True)
class VoteOutcome:
    """Immutable outcome of submitting an approval vote."""

    status: VoteStatus
    votes_for: int
    votes_against: int

    def to_dict(self) -> dict[str, Any]:
        """Produce JSON-serializable dictionary for HTTP wire response."""
        return {
            "status": self.status,
            "votes_for": self.votes_for,
            "votes_against": self.votes_against,
        }


@runtime_checkable
class AdminNotifier(Protocol):
    """Notification seam for operator payment hold alerts (Task 43 contract).

    Decouples voting and settlement orchestration from specific transport sinks.
    Task 43 implements this Protocol for Telegram, Slack, and email channels.
    """

    async def notify_hold_pending(self, hold: HoldRecord) -> None:
        """Notify operators that a payment hold requires review."""
        ...

    async def notify_hold_settled(self, hold: HoldRecord, outcome: Any) -> None:
        """Notify operators that a payment hold was approved and settled."""
        ...

    async def notify_hold_rejected(self, hold: HoldRecord, outcome: Any) -> None:
        """Notify operators that a payment hold was rejected."""
        ...


class LoggingAdminNotifier:
    """Default logging-stub implementation of AdminNotifier until Task 43 ships."""

    async def notify_hold_pending(self, hold: HoldRecord) -> None:
        logger.info(
            "admin_notify_hold_pending",
            hold_id=str(hold.hold_id),
            agent_id=str(hold.agent_id),
            amount_minor=hold.amount_minor,
            currency=hold.currency,
        )

    async def notify_hold_settled(self, hold: HoldRecord, outcome: Any) -> None:
        logger.info(
            "admin_notify_hold_settled",
            hold_id=str(hold.hold_id),
            agent_id=str(hold.agent_id),
            outcome=str(outcome),
        )

    async def notify_hold_rejected(self, hold: HoldRecord, outcome: Any) -> None:
        logger.info(
            "admin_notify_hold_rejected",
            hold_id=str(hold.hold_id),
            agent_id=str(hold.agent_id),
            outcome=str(outcome),
        )


