class HoldNotPendingError(FluxPayError):
    """Payment hold is no longer pending (already decided, settled, or rejected)."""

    code: str = "hold_not_pending"
    status: int = 409
    retryable: bool = False
    client_message: str = "payment hold is not in pending status"


ERROR_REGISTRY[HoldNotPendingError.code] = HoldNotPendingError


# ==============================================================================
# PURE DECISION POLICY FUNCTIONS (TESTABLE IN ISOLATION)
# ==============================================================================
def decide_from_votes(votes_for: int, votes_against: int) -> str:
    """Evaluate vote counts against the 2-man rule quorum policy.

    Asymmetry Rule:
    - If votes_against >= 1 and REJECTS_TERMINAL: outcome is 'rejected'.
    - If votes_for >= VOTES_REQUIRED: outcome is 'approved_settled'.
    - Otherwise: outcome is 'counted' (awaiting second voter).
    """
    if REJECTS_TERMINAL and votes_against >= 1:
        return "rejected"
    if votes_for >= VOTES_REQUIRED:
        return "approved_settled"
    return "counted"


def check_voter_role(voter_role: str) -> None:
    """Enforce administrator role for approval voting.

    Raises:
        ForbiddenError: If voter does not have 'admin' role.
    """
    if voter_role != "admin":
        raise ForbiddenError(message="insufficient permissions: admin role required to vote")


def classify_vote(
    *,
    already_voted: bool,
    votes_for: int,
    votes_against: int,
) -> str:
    """Classify vote state into a VoteOutcome status string."""
    if already_voted:
        return "already_voted"
    return decide_from_votes(votes_for, votes_against)


