"""Dual-Authorization: 2-Man Rule for Held Payments (Block H, Part 4).

==============================================================================
CONVERGENCE ESSAY: TWO-PHASE VOTE/SETTLE RATIONALE & CRASH-WINDOW SWEEP
==============================================================================
A fundamental safety law of FluxPay is that MONEY MOVES ONLY THROUGH TASK 31'S
SETTLEMENT DOOR (settle_approved). Approval orchestration does not move ledger
balances; it evaluates human governance consensus and safely unlocks the
exact-once settlement door.

The execution is intentionally split into two distinct operational phases:
Phase 1: Quorum Vote Commit (Database UnitOfWork)
- Locks the payment_holds record FOR UPDATE (asserting 'pending' state).
- Enforces role discipline ('admin' only) and self-vote exclusion (UNIQUE constraint
  on (hold_id, voter_sub)).
- Commits the approver's vote and audit row (`hold.vote`) atomically.
- If threshold is reached (approves >= 2), updates status to 'approved' and records
  `hold.approve2` audit row, committing the UnitOfWork.

Phase 2: Post-Commit Settlement Replay
- Because Task 31's settle_approved manages its own transaction boundaries across
  the ledger store and outbox, nesting it inside Phase 1's UnitOfWork would trigger
  transaction nesting deadlocks and connection starvation.
- Therefore, settlement executes immediately AFTER Phase 1 commits.
- If a server process crashes, hardware fails, or network partitions in the microsecond
  window between Phase 1 commit ('approved') and Phase 2 completion:
  The payment hold remains in status='approved', but the financial transaction has not
  settled (idempotency key remains PENDING).
- The ApprovalsWorker continuous poll loop detects approved holds older than the grace
  period (default 60s) and executes a crash-heal sweep:
  1. It performs an idempotency probe via `idempotency.lookup(conn, agent_id, idem_key)`.
  2. If the reservation is COMPLETED (replay outcome), the payment was already settled
     prior to the crash; the sweep safely skips without redundant work.
  3. If the reservation is PENDING, the sweep calls Task 31's `settle_approved`, records
     the `hold.settled` audit row, and emits operator notifications.
Task 31's deterministic transaction ID and reservation claim make this healing pass
strictly idempotent and crash-proof.

==============================================================================
ARCHITECTURAL DECISIONS & DOMAIN LAWS
==============================================================================
1. REJECT-TERMINATES ASYMMETRY (PRODUCT DECISION):
   Rejections are terminal immediately (REJECTS_TERMINAL = True). If any approver
   flags fraud, sanctions breach, or critical risk, the hold is terminated immediately
   regardless of whether another approver has voted 'approve'. Approvals must never race
   a known rejection. Two approvals + one rejection resolves decisively as REJECTED.

2. ADMIN-ONLY VOTER LAW & SEPARATION OF DUTIES:
   Only administrators possessing role 'admin' may vote on money movement. Support
   operators may inspect held queues, review audit trails, and assist merchants, but
   are strictly forbidden from approving fund releases (403 ForbiddenError).

3. "THE AGENT IS NOT A PARTY" (2-MAN RULE INTERPRETATION):
   Unlike human expense systems where creator != approver, holds in FluxPay are
   system-generated by autonomous AI agents when spending ceilings or velocity limits
   are breached. The agent is not a human party. The 2-man rule is strictly enforced
   as TWO DISTINCT HUMAN ADMINISTRATORS (DB uniqueness on (hold_id, voter_sub)).

4. NOTIFICATION DEDUP MARKER (IN-TABLE COLUMN):
   `payment_holds.notified_at` provides an in-table deduplication marker. An additive
   column avoids foreign key overhead and join latency on high-frequency hold queries.
   Crash between notification dispatch and DB update results in at most one duplicate
   alert, which is acceptable at-least-once operational semantics.

5. WHY NO SHARED APPROVAL FRAMEWORK WITH TREASURY (TASK 47 NOTE):
   Treasury cold payouts (Task 47) also implement a 2-man rule, but operate against
   different tables, distinct risk profiles, different audit retention requirements,
   and independent operational cadences. Sharing an abstract "approval framework" would
   tightly couple merchant risk quarantine with internal treasury management.
   Boring code duplication wins at this scale.

6. TASK 43 NOTIFIER SEAM:
   AdminNotifier Protocol defines the decoupled seam for operator notifications.
   Task 42 ships with a logging stub; Task 43 implements the production alerting
   transports (Slack, Telegram, Email) against this exact Protocol.
"""

